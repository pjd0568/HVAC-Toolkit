def glycol_concentrations(fluid: FluidId) -> tuple[int, ...]:
    return GLYCOL_CONCENTRATIONS_PCT[fluid]


def glycol_grid(fluid: FluidId, concentration_pct: int):
    try:
        return _GLYCOL_GRIDS[fluid][concentration_pct]
    except KeyError as exc:
        raise ValueError(f"no data for {fluid!r} at {concentration_pct}%") from exc


def glycol_freeze_point_c(fluid: FluidId, concentration_pct: int) -> float:
    """Catalogue freeze point (°C) for a fluid at the stated concentration."""
    grid = glycol_grid(fluid, concentration_pct)
    return grid[0][4]


